# -*- coding: utf-8 -*-
"""paeg_lang_style.rules_enhanced — 通则化语言规范检测（增强层 ⭐）。

**设计哲学（用户关切 §3.109 ⭐）**：语言规范的本质是**指挥 LLM 使用完整的词、
完整的句法**，而非对特定词做列举式替换。本模块实现**通则推理**：

1. **词法完整通则**：凡表达"状态/感受"的单字形容词（乏/沉/累/苦/慌/虚/弱/低/烦/闷/倦/困/急/慌/乱）
   一律应扩展为完整双字词形——这是**通则**，LLM 理解后自行泛化到所有场景
   （"倦"→"疲倦"只是通则的一个实例，不是唯一目标）。
2. **句法完整通则**：主谓宾齐全/动宾搭配自然/介词必带宾语——句子成分完整是通则。

与 rules.py（列举式规则）的区别：
- rules.py：具体模式匹配（"倦""道出"等），返回具体修正建议
- rules_enhanced.py：**通则推理**（单字状态词表 + 通用结构检查），返回通则提示，
  供 LLM 重写时应用——指挥 LLM 泛化，而非逐词修补

用法：
    from paeg_lang_style.rules_enhanced import (
        check_lexicon_general_rule,   # 词法完整通则检测
        check_syntax_general_rule,    # 句法完整通则检测
        build_lexicon_rule_prompt,    # 生成词法通则提示词（注入 LLM 系统提示词）
        build_syntax_rule_prompt,     # 生成句法通则提示词
    )
"""

from __future__ import annotations

import re
from typing import List, Tuple


# ─────────────────────────────────────
# 通则 1：词法完整 —— 单字状态词表（通则推理，非列举替换）
# 凡表达"状态/感受"的单字形容词，一律扩展为完整双字词形。
# 这指挥 LLM：遇到任何单字状态词 → 自动补全为完整词，而非记住"倦→疲倦"一个替换。
# ─────────────────────────────────────
# (单字, 完整双字词形)
SINGLE_CHAR_STATE_WORDS: List[Tuple[str, str]] = [
    ("倦", "疲倦"), ("乏", "疲乏"), ("沉", "沉重"), ("累", "疲惫"),
    ("苦", "苦涩"), ("慌", "慌乱"), ("虚", "虚弱"), ("弱", "虚弱"),
    ("低", "低落"), ("烦", "烦躁"), ("闷", "烦闷"), ("困", "困倦"),
    ("急", "着急"), ("乱", "慌乱"),
]

# 通则描述（供 LLM 系统提示词使用）
LEXICON_GENERAL_RULE = """### 词法完整通则（⭐ 指挥 LLM 使用完整词，而非记忆个别替换）

**通则**：凡表达"状态/感受"的单字形容词，一律扩展为完整双字词形。

**判断方法**：遇到单字状态词（倦/乏/沉/累/苦/慌/虚/弱/低/烦/闷/困/急/乱等）时，
自动补全为对应完整词形——这不是"记住某个替换"，而是**应用通则**：

- "倦" → "疲倦"（"觉得疲倦了"）
- "乏" → "疲乏"（"身体上的疲乏"）
- "沉" → "沉重"（"心里有点沉重"）
- "累" → "疲惫"（"有点疲惫"）
- "苦" → "苦涩"（"心里苦涩"）
- "慌" → "慌乱"（"心里慌乱"）
- "虚/弱" → "虚弱"（"身体虚弱"）
- "低" → "低落"（"情绪低落"）
- "烦" → "烦躁"（"心里烦躁"）
- "闷" → "烦闷"（"心里烦闷"）
- "困" → "困倦"（"有点困倦"）
- "急" → "着急"（"不要着急"）
- "乱" → "慌乱"（"心里慌乱"）

**例外**：真正的祈使指令（"请做这道题""看这里"）可保留简洁动词；
单字词本身语义完整且无对应双字词（"走""看""吃"）不受限。

**本质**：不是修补特定词，而是让语言**统一使用完整词形**——这需要你（LLM）
在生成时主动应用通则，遇到任何单字状态词都自动补全。"""


def check_lexicon_general_rule(text: str) -> List[str]:
    """词法完整通则检测：找出文本中的单字状态词，提示应扩展为完整双字词形。

    返回通则提示（如 "'倦' 是单字状态词，按词法完整通则应扩展为 '疲倦'"）。
    """
    if not text:
        return []
    issues: List[str] = []
    for single, full in SINGLE_CHAR_STATE_WORDS:
        if single in text:
            # 跳过已是完整词形的情况（如"疲倦"里的"倦"）
            if full in text and text.count(single) <= text.count(full):
                continue
            issues.append(
                f"'{single}' 是单字状态词——按词法完整通则应扩展为完整词形'{full}'"
                f"（如'觉得{full}'），请应用通则而非记忆个别替换"
            )
    return issues[:10]


def build_lexicon_rule_prompt() -> str:
    """生成词法通则提示词（供注入 LLM 系统提示词）。"""
    return LEXICON_GENERAL_RULE


# ─────────────────────────────────────
# 通则 2：句法完整 —— 句子成分齐全（主谓宾/动宾搭配/介词规范）
# 这是通则：每个句子必须完整，LLM 生成时自行检查，而非修补特定句式。
# ─────────────────────────────────────
SYNTAX_GENERAL_RULE = """### 句法完整通则（⭐ 指挥 LLM 使用完整句法，而非修补特定句式）

**通则**：每个句子必须具有完整的主谓宾（陈述句）或主系表（判断/描述句）结构。

**判断方法**（每句输出前自查）：
1. **有主语吗？** 老师对学生说话时禁止无主语短语单独成句（"不催你。"→"老师不催你，你慢慢来。"）
2. **有谓语吗？** 禁止"没头没尾"的祈使碎片（"一句话总结""记住这一句"→"我们可以用一句话来记住这一点"）
3. **有宾语吗？** 动词必须带恰当宾语（"我想与你探讨。"→"我想与你探讨这个问题。"）
4. **动宾搭配自然吗？** 禁止强行组合（"带着重量"→"有很重的分量"；"进行一个分析"→"分析"）
5. **介词带宾语了吗？** 禁止悬空（"关于学习方面。"→"在学习方面，要重视方法。"）
6. **复合句分句有主语吗？** （"因为学习了，进步了。"→"因为学习了，所以我进步了。"）
7. **"听"类动词带补语了吗？** 禁止"听着你"悬空（→"听你说说"）
8. **修饰成分够吗？** 抽象名词做宾语须有中心名词（"作为主力"→"作为主力工具"）

**合法省略边界**（仅三种情况可省略主语）：祈使指令 / 上下文同一主语 / 简短应答。
讲解、总结、承诺、描述——必须显式主语。

**本质**：不是修补特定句式，而是让语言**每个句子成分齐全**——这需要你（LLM）
在生成时主动应用通则，任何句子输出前自查 8 项。"""


def check_syntax_general_rule(text: str) -> List[str]:
    """句法完整通则检测：句子成分齐全性检查（通则版）。

    检查项（覆盖 rules.py 的 8 类 + 通则推理）：
    1. 无主语命令句/短语单独成句
    2. 悬空宾语（与你探讨$）
    3. 动宾搭配（带着重量）
    4. 复合句缺主语（因为…，所以…）
    5. 介词悬空
    6. "听着你"悬空
    """
    if not text:
        return []
    issues: List[str] = []

    # 句法通则检测（调用 rules.py 的列举式检测作为基础，再叠加通则推理）
    try:
        from .rules import check_ellipsis as _ce
        base_issues = _ce(text)
        issues.extend(base_issues)
    except Exception:
        pass

    # 通则推理 1：无主语短语单独成句（通则版——覆盖所有"别/不/先+单字动词"模式）
    no_subject_patterns = [
        r"^(别|不|先|再|不要|不必|无需|不用|暂时)[^，。；]{1,8}($|[，。；])",
        r"^(别|不要|不必|无需|不用)[^，。；]{0,6}(急|慌|怕|赶|贪|催|省|凑|堆)($|[，。；])",
    ]
    for pat in no_subject_patterns:
        for sent in re.split(r"[。；\n]", text):
            s = sent.strip()
            if re.match(pat, s) and len(s) < 30:
                issues.append(
                    f"'{s[:20]}…' 无主语短语单独成句——句法完整通则要求补主语"
                    f"（如'老师不催你，你慢慢来'）"
                )

    # 通则推理 2：悬空宾语（"与你探讨$" 等，通则版）
    dangling = re.findall(r"与(你|您)(探讨|分享|交流)$", text, re.M)
    for d in dangling:
        issues.append(
            f"'与你{d[1]}' 动词悬空缺宾语——句法完整通则要求补足"
            f"（如'与你{d[1]}这个问题'）"
        )

    # 通则推理 3：动宾搭配（"带着重量"等，通则版）
    if re.search(r"带着(重量|分量|意义|温度)", text):
        issues.append("'带着重量/分量/意义' 动宾搭配不当——动词须自然接宾语（如'这句话有很重的分量'）")

    # 通则推理 4：复合句缺主语（通则版）
    for sent in re.split(r"[。；\n]", text):
        s = sent.strip()
        if re.match(r"^(因为|由于|如果|既然|虽然|尽管|即使)[^，。；]{1,15}，", s) and \
                not re.search(r"(我们|我|你|学生|它|他|她)", s):
            issues.append(
                f"'{s[:24]}…' 复合句分句缺主语——句法完整通则要求每个分句有主语"
                f"（如'因为学习了，所以我进步了'）"
            )

    # 通则推理 5：介词悬空（通则版）——覆盖"介词短语后接无主句" + "介词短语单独成句"
    for sent in re.split(r"[。；\n]", text):
        s = sent.strip()
        # 介词短语单独成句（如"关于学习方面。"——缺主句）
        if re.match(r"^(关于|对于|通过|根据|按照|依据)[^，。；]{1,15}($|[，。；])", s) and len(s) < 30:
            issues.append(
                f"'{s[:20]}…' 介词短语单独成句——句法完整通则要求介词带宾语且后接完整主句"
                f"（如'关于这个问题，我有如下看法'）"
            )
        # 介词短语后接无主句
        elif re.match(r"^(关于|对于|通过|根据)[^，。；]{1,12}，", s) and \
                not re.search(r"(我们|我|你|学生|它|他|她)", s):
            issues.append(
                f"'{s[:24]}…' 介词短语后接无主句——句法完整通则要求介词带宾语且后接完整主句"
            )

    # 去重（保序）
    seen = set()
    deduped = []
    for i in issues:
        if i not in seen:
            seen.add(i)
            deduped.append(i)
    return deduped[:12]


def build_syntax_rule_prompt() -> str:
    """生成句法通则提示词（供注入 LLM 系统提示词）。"""
    return SYNTAX_GENERAL_RULE
