class ForbiddenWords:
    """动态违禁词库：内置词库 + 外部 JSON 热加载 + 运行时增删。"""

    def __init__(self, builtin: Optional[List[str]] = None):
        self._words: List[str] = list(dict.fromkeys(builtin if builtin is not None else _BUILTIN_FORBIDDEN))

    # ── 词库内容 ──
    @property
    def words(self) -> List[str]:
        return list(self._words)

    def add(self, word: str) -> bool:
        """运行时新增违禁词（动态维护 ⭐）。"""
        if isinstance(word, str) and word and word not in self._words:
            self._words.append(word)
            return True
        return False

    def remove(self, word: str) -> bool:
        """运行时移除违禁词。"""
        if word in self._words:
            self._words.remove(word)
            return True
        return False

    def load_json(self, path: Optional[str] = None) -> int:
        """合并外部 JSON 违禁词库（动态维护 ⭐）。

        JSON 结构：{"extra_forbidden": [...], "pseudo_empathy_verbs": [...], "ai_tells_extra": [...]}
        返回新增词条数；文件缺失/损坏 → 0（不抛异常）。
        """
        if path is None:
            path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "forbidden_words.json")
        try:
            with open(path, encoding="utf-8") as f:
                data = json.load(f)
        except Exception:
            return 0
        added = 0
        for key in ("extra_forbidden", "pseudo_empathy_verbs", "ai_tells_extra"):
            for w in data.get(key, []):
                if self.add(w):
                    added += 1
        return added

    # ── 检测 ──
    def detect(self, text: str) -> List[str]:
        """检测文本命中的违禁词。返回命中列表（保序）。"""
        if not text:
            return []
        return [w for w in self._words if w in text]

    def detect_count(self, text: str) -> int:
        """命中违禁词总数（一个词出现多次算多次）。"""
        if not text:
            return 0
        return sum(text.count(w) for w in self._words)
