    (r"开始算|先算|来算|算算|算一下|算个", "『算』是『计算』的省略，应改为完整词形『计算』（『我们开始计算』『先计算一下』）"),
    (r"开始看|先看|来看|看看", "『看』若指『观察/查看』应用完整形式『观察』『查看』（教学场景更规范）"),
